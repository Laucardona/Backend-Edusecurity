-- Permisos por rol (I1, tarea 1.2; diseño §8.1, ADR-012).
-- Los endpoints se protegen por permiso, no por rol: un rol es un conjunto de permisos que el
-- administrador puede cambiar (PUT /api/roles/{id}/permisos). El access token lleva los permisos.
-- Compatible con PostgreSQL 16 y H2 en modo PostgreSQL.

CREATE TABLE permisos (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    codigo        VARCHAR(60)   NOT NULL,
    descripcion   VARCHAR(250),
    PRIMARY KEY (id),
    CONSTRAINT uk_permisos_codigo UNIQUE (codigo)
);

CREATE TABLE rol_permisos (
    rol_id        BIGINT        NOT NULL,
    permiso_id    BIGINT        NOT NULL,
    PRIMARY KEY (rol_id, permiso_id),
    CONSTRAINT fk_rol_permisos_rol FOREIGN KEY (rol_id) REFERENCES roles (id) ON DELETE CASCADE,
    CONSTRAINT fk_rol_permisos_permiso FOREIGN KEY (permiso_id) REFERENCES permisos (id) ON DELETE CASCADE
);

